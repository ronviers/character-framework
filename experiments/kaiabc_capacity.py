# order of edges around the ring and their (k0, kA): U->T, T->D, D->S, S->U  (forward)
#                                                     T->U, D->T, S->D, U->S  (backward)
K0 = {("U", "T"): 0.0, ("T", "D"): 0.0, ("D", "S"): 0.31, ("S", "U"): 0.11,
      ("T", "U"): 0.21, ("D", "T"): 0.0, ("S", "D"): 0.0, ("U", "S"): 0.0}
KA = {("U", "T"): 0.479077, ("T", "D"): 0.212923, ("D", "S"): -0.319385, ("S", "U"): -0.133077,
      ("T", "U"): 0.0798462, ("D", "T"): 0.173000, ("S", "D"): 0.505692, ("U", "S"): 0.0532308}
K_HALF = 0.43            # uM
M_STOI = 1.0             # KaiA dimers inactivated per S-KaiC monomer
KAIA = 1.3               # uM (total)
KAIC = 3.4               # uM (total)
IC = (0.68, 1.36, 0.34)  # T0, D0, S0 (uM)  -- Rust Fig 4A
