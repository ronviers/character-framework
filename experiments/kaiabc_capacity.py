FWD = [("U", "T"), ("T", "D"), ("D", "S"), ("S", "U")]   # the forward ring (ordered phosphorylation)
BWD = [("T", "U"), ("D", "T"), ("S", "D"), ("U", "S")]


def rate(edge, S, kaia=KAIA, k0=None, ka=None):
    k0 = K0 if k0 is None else k0
    ka = KA if ka is None else ka
    A = max(0.0, kaia - 2.0 * M_STOI * S)
    return k0[edge] + ka[edge] * A / (K_HALF + A)


def rhs(t, y, kaia=KAIA, k0=None, ka=None):
    T, D, S = y
    U = KAIC - T - D - S
    r = lambda e: rate(e, S, kaia, k0, ka)
    dT = r(("U", "T")) * U + r(("D", "T")) * D - (r(("T", "U")) + r(("T", "D"))) * T
    dD = r(("T", "D")) * T + r(("S", "D")) * S - (r(("D", "T")) + r(("D", "S"))) * D
    dS = r(("D", "S")) * D + r(("U", "S")) * U - (r(("S", "D")) + r(("S", "U"))) * S
    return [dT, dD, dS]


def simulate(T=600.0, kaia=KAIA, y0=IC, k0=None, ka=None, n=24000):
    return solve_ivp(rhs, (0, T), y0, args=(kaia, k0, ka), method="LSODA",
                     rtol=1e-9, atol=1e-11, dense_output=True, t_eval=np.linspace(0, T, n))


def ring_currents(sol, burn=0.5, kaia=KAIA, k0=None, ka=None):
    """Period-averaged net current on each of the 4 ring edges. For a single loop (b1=1) at periodic
    steady state these must be EQUAL (Kirchhoff) -- that equality is itself a forced-not-fitted check.
    Returns (J_fwd_edges dict, J_cyc, conc_amp)."""
    i0 = int(len(sol.t) * burn)
    t = sol.t[i0:]
    T, D, S = sol.y[0, i0:], sol.y[1, i0:], sol.y[2, i0:]
    U = KAIC - T - D - S
    conc = {"U": U, "T": T, "D": D, "S": S}
    J = {}
    for (a, b) in FWD:
        ra = np.array([rate((a, b), s, kaia, k0, ka) for s in S])
        rb = np.array([rate((b, a), s, kaia, k0, ka) for s in S])
        Jt = ra * conc[a] - rb * conc[b]               # net a->b current, time series
        J[(a, b)] = float(np.trapezoid(Jt, t) / (t[-1] - t[0]))
    J_cyc = float(np.mean(list(J.values())))
    amp = float((T + D + S).max() - (T + D + S).min())  # total-phosphorylation amplitude
    return J, J_cyc, amp


def period_of(sol, burn=0.4):
    """Period (h) from peaks of total phosphorylation P = T+D+S."""
    i0 = int(len(sol.t) * burn)
    t = sol.t[i0:]
    P = sol.y[0, i0:] + sol.y[1, i0:] + sol.y[2, i0:]
    d = np.diff(P); pk = np.where((d[:-1] > 0) & (d[1:] <= 0))[0] + 1
    pk = pk[P[pk] > P.mean()]
    return float(np.mean(np.diff(t[pk]))) if len(pk) >= 2 else np.nan


def floquet_multipliers(sol):
    """K_metric, forced-not-fitted: integrate the variational equation over one period to get the
    monodromy matrix; its eigenvalues (Floquet multipliers) tell us how many SLOW (marginal, |mu|~1)
    directions the attractor has beyond the fixed point. One ~1 (the phase) + the rest contracting
    => slow-manifold dim = 1."""
    Tp = period_of(sol)
    if not np.isfinite(Tp):
        return Tp, None, np.nan
    # a point on the limit cycle (well past burn-in)
    x0 = sol.sol(sol.t[-1] - Tp)
    eps = 1e-6

    def jac(x):
        J = np.zeros((3, 3))
        f0 = np.array(rhs(0, x))
        for k in range(3):
            xp = np.array(x, float); xp[k] += eps
            J[:, k] = (np.array(rhs(0, xp)) - f0) / eps
        return J

    def aug(t, z):
        x = z[:3]; Phi = z[3:].reshape(3, 3)
        return np.concatenate([rhs(0, x), (jac(x) @ Phi).ravel()])

    z0 = np.concatenate([x0, np.eye(3).ravel()])
    s = solve_ivp(aug, (0, Tp), z0, method="LSODA", rtol=1e-9, atol=1e-11)
    M = s.y[3:, -1].reshape(3, 3)
    mu = np.sort(np.abs(np.linalg.eigvals(M)))[::-1]
    n_slow = int(np.sum(mu > 0.5))      # marginal/slow directions (one is the phase, ~1)
    return Tp, mu, n_slow


def betti1():
    """b1 of the reaction graph = E - V + 1 for the connected single component."""
    nodes = {"U", "T", "D", "S"}
    edges = {frozenset(e) for e in FWD}     # 4 undirected edges
    return len(edges) - len(nodes) + 1


